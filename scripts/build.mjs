// Builds dist/backend.js and dist/frontend.js with Bun.
//  1. verify originals and generate the patched scene/recall modules (scripts/generate-core.mjs), then
//     generate the patched screen from the unmodified original (src/memory/ui/patch.mjs) and the
//     override sheet into src/*.generated.js  (what upstream's extension/build.py did for the memory screen, plus our patches)
//  2. bun build backend (--target bun) and frontend (--target browser), both --format esm.
// BUN_BIN overrides the bun executable (the mise shim may be broken on this machine).
import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { patchMemory } from '../src/memory/ui/patch.mjs';
import { verify } from './verify-original.mjs';
import { generateCore } from './generate-core.mjs';

const bad = verify('.');
if (bad.length) { console.error('original files differ from their pins:\n' + bad.join('\n')); process.exit(1); }
generateCore();
const read = f => readFileSync(new URL('../' + f, import.meta.url), 'utf8');
const pkg = JSON.parse(read('package.json'));
const GENERATED = '// GENERATED by scripts/build.mjs from the unmodified originals + patches. Do not edit.\n';
writeFileSync(new URL('../src/memory/ui/runtime.generated.js', import.meta.url), GENERATED + patchMemory({ runtime: read('src/memory/ui/runtime.orig.js'), uiCss: read('src/memory/ui/ui.orig.css'), themeCss: read('src/memory/ui/theme.orig.css'), version: pkg.version }));
writeFileSync(new URL('../src/styles.generated.js', import.meta.url), GENERATED + `export const MEMORY_OVERRIDES = ${JSON.stringify(read('src/overrides.memory.css'))};\n`);

const bun = process.env.BUN_BIN || 'bun';
mkdirSync('dist', { recursive: true });
for (const [entry, target] of [['backend', 'bun'], ['frontend', 'browser']]) {
    const p = spawnSync(bun, ['build', `src/${entry}.ts`, '--outfile', `dist/${entry}.js`, '--target', target, '--format', 'esm'], { stdio: 'inherit' });
    if (p.error || p.status !== 0) throw p.error || Error(`Bun build failed: status=${p.status} signal=${p.signal}`);
}
// Lumiverse's backend scanner rejects `Buffer.from(..., "base64")` ("base64 decoding"). The pinned vectors.cjs uses it in
// unpack(); rewrite just that decode in the bundle (atob gives identical bytes) and keep the pinned original untouched.
const backendUrl = new URL('../dist/backend.js', import.meta.url);
const bundled = readFileSync(backendUrl, 'utf8');
const NEEDLE = /const buf = Buffer\.from\(text, ["']base64["']\);\s*return new Float32Array\(buf\.buffer, buf\.byteOffset, buf\.byteLength \/ 4\);/g;
const hits = bundled.match(NEEDLE) || [];
if (hits.length !== 1) throw new Error(`expected exactly 1 vectors unpack() decode in dist/backend.js, found ${hits.length}`);
writeFileSync(backendUrl, bundled.replace(NEEDLE, () => 'const bin = atob(text);\n    const bytes = new Uint8Array(bin.length);\n    for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);\n    return new Float32Array(bytes.buffer, 0, bytes.length >> 2);'));

console.log(JSON.stringify({ ok: true, artifacts: ['dist/backend.js', 'dist/frontend.js'] }));
